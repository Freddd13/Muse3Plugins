const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const p={};vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../ExpressionProgress.js'),'utf8'),p);
const plain=v=>JSON.parse(JSON.stringify(v));
const note={id:'0:0:0',tick:0,track:0,index:0,pitch:60,writtenPitch:60,writtenTpc:14,end:480,duration:480,velocityType:0,velocityRaw:0,bpm:120};
const applied={...note,oldType:1,oldRaw:106};
const records=plain(p.record(null,{velocity:[applied],tempos:[{tick:240,bpm:90}]}));
const original=JSON.stringify(records),changed={...note,velocityType:1,velocityRaw:106};
assert.equal(Object.keys(p.reconcile(records,[changed]).velocity).length,1);
assert.equal(Object.keys(p.reconcile(records,[note]).velocity).length,0);
assert.equal(Object.keys(p.reconcile(records,[changed]).velocity).length,1);
assert.equal(JSON.stringify(records),original,'Undo must keep the adopted value for redo');
assert.equal(Object.keys(p.reconcile(records,[{...changed,writtenPitch:61}]).velocity).length,0);
assert.equal(Object.keys(p.reconcile(records,[]).velocity).length,0);
assert.equal(Object.keys(p.reconcile(records,[{...changed,track:4}]).velocity).length,0);
assert.equal(Object.keys(p.reconcile(records,[note],{points:[{tick:0,bpm:90}]}).tempos).length,1);
assert.equal(Object.keys(p.reconcile(records,[note],{points:[{tick:0,bpm:120}]}).tempos).length,0);
assert.equal(Object.keys(p.reconcile(records,[note],{points:[{tick:0,bpm:90}]}).tempos).length,1);
assert.equal(p.sameNotation([note],[{...note,velocity:110,velocityRaw:20,bpm:80,onSeconds:3}]),true);
for(const change of [{writtenPitch:61},{duration:240},{end:240},{tieBack:true},{track:4},{logicalEnd:960}])assert.equal(p.sameNotation([note],[{...note,...change}]),false);
const other={...note,track:4,id:'0:4:0'};
assert.equal(p.sameNotation([note,other],[other,note]),true);
assert.equal(p.sameNotation([note,other],[note]),false);
console.log('Expression refresh: undo/redo, tempo points, physical notes and unchanged notation passed.');
