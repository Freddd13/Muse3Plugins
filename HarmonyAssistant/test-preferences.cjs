const fs = require('fs'), vm = require('vm'), assert = require('assert');
const prefs = {};
vm.createContext(prefs);
vm.runInContext(fs.readFileSync(__dirname + '/Preferences.js', 'utf8').replace(/^\.pragma library\s*/, ''), prefs);
assert.equal(prefs.defaults().avoidScoreContent, false);
const older = prefs.defaults();
delete older.avoidScoreContent;
assert.equal(prefs.clean(older).avoidScoreContent, false);
const chosen = prefs.defaults();
chosen.avoidScoreContent = true;
chosen.chordMask = false;
chosen.ribbonAlign = 3;
chosen.ribbonPosition = 72;
const restored = prefs.clean(JSON.parse(JSON.stringify(prefs.clean(chosen))));
assert.equal(restored.avoidScoreContent, true);
assert.equal(restored.chordMask, false);
assert.equal(restored.ribbonAlign, 3);
assert.equal(restored.ribbonPosition, 72);
assert.equal(prefs.clean({...chosen, avoidScoreContent: 'true'}).avoidScoreContent, false);
console.log('和弦外观设置：旧配置读取、保存恢复和两个独立开关检查通过。');
